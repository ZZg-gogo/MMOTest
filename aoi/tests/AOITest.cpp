#include "TowerAoi.h"

#include <iostream>

int main()
{
    std::cout << "============================================================\n";
    std::cout << "                 TOWER AOI FULL TEST\n";
    std::cout << "              Enter -> Move -> Leave\n";
    std::cout << "============================================================\n\n";


    // 地图：
    //
    // 宽度：1000
    // 高度：1000
    //
    // 世界坐标范围：
    //
    // X: -500 ~ 500
    // Y: -500 ~ 500
    //
    // 每个 Tower：
    //
    // 100 x 100
    //
    TowerAoi aoi(
        1,          // spaceId
        1000,       // width
        1000,       // height
        100,        // towerWidth
        100         // towerHeight
    );


    // ============================================================
    // Test 1
    // Player 1 Enter
    // ============================================================

    std::cout << "============================================================\n";
    std::cout << "Test 1: Player 1 Enter\n";
    std::cout << "============================================================\n";

    aoi.OnObjectEnter(
        1,
        Vec2(0, 0),
        200
    );

    aoi.PrintWatchers();

    std::cout << "\n";


    // ============================================================
    // Test 2
    // Player 2 Enter
    //
    // Player1: (0, 0)
    // Player2: (100, 0)
    //
    // 距离 = 100
    //
    // 两个人视野都是 200
    //
    // 应该互相可见
    // ============================================================

    std::cout << "============================================================\n";
    std::cout << "Test 2: Player 2 Enter Near Player 1\n";
    std::cout << "============================================================\n";

    aoi.OnObjectEnter(
        2,
        Vec2(100, 0),
        200
    );

    aoi.PrintWatchers();

    std::cout << "\n";


    // ============================================================
    // Test 3
    // Player 3 Enter
    //
    // Player3: (400, 0)
    //
    // 距离：
    //
    // Player1 -> Player3 = 400
    // Player2 -> Player3 = 300
    //
    // 视野 = 200
    //
    // 所以 Player3 和其他人都不可见
    // ============================================================

    std::cout << "============================================================\n";
    std::cout << "Test 3: Player 3 Enter Far Away\n";
    std::cout << "============================================================\n";

    aoi.OnObjectEnter(
        3,
        Vec2(400, 0),
        200
    );

    aoi.PrintWatchers();

    std::cout << "\n";


    // ============================================================
    // Test 4
    // Player 3 Move
    //
    // Player3:
    //
    // (400, 0)
    //      ↓
    // (150, 0)
    //
    // 现在：
    //
    // Player1 -> Player3 = 150
    // Player2 -> Player3 = 50
    //
    // 所以 Player3 应该进入 Player1 和 Player2 的视野
    // ============================================================

    std::cout << "============================================================\n";
    std::cout << "Test 4: Player 3 Move Into View\n";
    std::cout << "============================================================\n";

    aoi.OnObjectMove(
        3,
        Vec2(150, 0)
    );

    aoi.PrintWatchers();

    std::cout << "\n";


    // ============================================================
    // Test 5
    // Player 1 Move Far Away
    //
    // Player1:
    //
    // (0, 0)
    //      ↓
    // (-400, 0)
    //
    // 此时：
    //
    // Player1 和 Player2 不可见
    // Player1 和 Player3 不可见
    //
    // Player2 和 Player3 仍然可见
    // ============================================================

    std::cout << "============================================================\n";
    std::cout << "Test 5: Player 1 Move Far Away\n";
    std::cout << "============================================================\n";

    aoi.OnObjectMove(
        1,
        Vec2(-400, 0)
    );

    aoi.PrintWatchers();

    std::cout << "\n";


    // ============================================================
    // Test 6
    // Player 1 Move Back
    //
    // Player1:
    //
    // (-400, 0)
    //      ↓
    // (0, 0)
    //
    // Player1 应该重新进入
    //
    // Player2
    // Player3
    //
    // 的视野
    // ============================================================

    std::cout << "============================================================\n";
    std::cout << "Test 6: Player 1 Move Back Into View\n";
    std::cout << "============================================================\n";

    aoi.OnObjectMove(
        1,
        Vec2(0, 0)
    );

    aoi.PrintWatchers();

    std::cout << "\n";


    // ============================================================
    // Test 7
    // Player 2 Leave
    //
    // Player2 退出地图
    //
    // 预期：
    //
    // Player1 看不到 Player2
    // Player3 看不到 Player2
    //
    // 同时：
    //
    // Player2 的 Watcher 被删除
    // Player2 的 Marker 被删除
    //
    // Player1 和 Player3 是否可见，
    // 取决于距离：
    //
    // Player1 (0,0)
    // Player3 (150,0)
    //
    // 距离 = 150
    //
    // 所以仍然互相可见
    // ============================================================

    std::cout << "============================================================\n";
    std::cout << "Test 7: Player 2 Leave\n";
    std::cout << "============================================================\n";

    aoi.OnObjectLeave(2);

    aoi.PrintWatchers();

    std::cout << "\n";


    // ============================================================
    // Test 8
    // Player 3 Leave
    //
    // 预期：
    //
    // Player1 的 Visible 为空
    // Player3 不存在
    // ============================================================

    std::cout << "============================================================\n";
    std::cout << "Test 8: Player 3 Leave\n";
    std::cout << "============================================================\n";

    aoi.OnObjectLeave(3);

    aoi.PrintWatchers();

    std::cout << "\n";


    // ============================================================
    // Test 9
    // Player 1 Leave
    //
    // 最后地图没有任何玩家
    //
    // 预期：
    //
    // PrintWatchers 没有任何输出
    // ============================================================

    std::cout << "============================================================\n";
    std::cout << "Test 9: Player 1 Leave\n";
    std::cout << "============================================================\n";

    aoi.OnObjectLeave(1);

    aoi.PrintWatchers();

    std::cout << "\n";


    std::cout << "============================================================\n";
    std::cout << "ALL ENTER -> MOVE -> LEAVE TESTS FINISHED\n";
    std::cout << "============================================================\n";

    return 0;
}